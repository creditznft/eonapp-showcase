/** W401 — local-first creator asset rights and provenance receipts. */

export const CREATOR_ASSET_PROVENANCE_SCHEMA = 'eonapp.creator.asset-provenance.v1';
export const CREATOR_ASSET_SOURCE_TYPES = Object.freeze([
  Object.freeze({ id: 'user-owned', label: 'My original / owned asset', review: 'Confirm that you control the rights needed for this use.' }),
  Object.freeze({ id: 'licensed', label: 'Licensed or stock asset', review: 'Keep the licence, permitted use, and attribution requirements with your records.' }),
  Object.freeze({ id: 'public-domain', label: 'Public-domain or clearly dedicated asset', review: 'Verify the source actually states public-domain or an applicable dedication.' }),
  Object.freeze({ id: 'provider-generated', label: 'Generated by my selected provider', review: 'Review the provider’s current terms, training/data disclosures, and commercial-use conditions yourself.' }),
  Object.freeze({ id: 'permission-granted', label: 'Permission granted by rights holder', review: 'Keep the permission record outside this browser and note its scope.' }),
  Object.freeze({ id: 'unknown', label: 'Unknown / needs review', review: 'Do not publish or represent this asset as cleared until you can verify its origin and rights.' })
]);

const SECRET_LIKE = /(?:sk-[a-z0-9_-]{12,}|api[_ -]?key\s*[:=]|bearer\s+[a-z0-9._-]{12,}|-----begin(?: [a-z]+)? private key-----|seed phrase|mnemonic)/i;

function cleanText(value = '', max = 500) {
  const safe = Array.from(String(value || ''), (character) => {
    const code = character.codePointAt(0) || 0;
    return code >= 32 && code !== 127 ? character : ' ';
  }).join('');
  return safe.replace(/\s+/g, ' ').trim().slice(0, max);
}

function findSourceType(id = '') {
  return CREATOR_ASSET_SOURCE_TYPES.find((item) => item.id === String(id || '').trim()) || CREATOR_ASSET_SOURCE_TYPES.at(-1);
}

function makeId() {
  try { return `asset-${crypto.randomUUID()}`; } catch { return `asset-${Date.now()}-${Math.random().toString(16).slice(2, 10)}`; }
}

export function createCreatorAssetReceipt(input = {}) {
  const title = cleanText(input.title, 180);
  const source = findSourceType(input.sourceType);
  const reference = cleanText(input.reference, 500);
  const attribution = cleanText(input.attribution, 280);
  const note = cleanText(input.note, 900);
  if (!title) throw new Error('Add a short asset name before creating a local provenance receipt.');
  const joined = [title, reference, attribution, note].join('\n');
  if (SECRET_LIKE.test(joined)) throw new Error('Do not put a key, password, recovery phrase, or other secret into an asset receipt.');
  const requiresReview = source.id === 'unknown' || !reference;
  return Object.freeze({
    schema: CREATOR_ASSET_PROVENANCE_SCHEMA,
    id: makeId(),
    title,
    sourceType: source.id,
    sourceLabel: source.label,
    reference,
    attribution,
    note,
    rightsStatus: requiresReview ? 'needs-review' : 'creator-reported',
    requiresReview,
    reviewNote: source.review,
    createdAt: new Date().toISOString(),
    storage: 'current-page-memory-only',
    proofOfRights: false,
    upload: false,
    externalVerification: false,
    publicationApproval: false
  });
}

export function buildCreatorAssetReceiptExport(receipts = []) {
  const rows = Array.isArray(receipts) ? receipts.slice(0, 100) : [];
  return Object.freeze({
    schema: `${CREATOR_ASSET_PROVENANCE_SCHEMA}.export`,
    exportedAt: new Date().toISOString(),
    receipts: rows,
    limitations: Object.freeze([
      'This is a creator-reported local record, not a licence, legal advice, ownership proof, rights clearance, content-ID result, or publication approval.',
      'No media file, raw upload, provider credential, browser history, private chat, or secret is included in this export.',
      'Do not rely on a generic “fair use” label. Verify the actual rights and destination rules for each asset.'
    ])
  });
}

export function getCreatorAssetSourceType(id = '') {
  return findSourceType(id);
}

export function getCreatorAssetProvenanceTruth() {
  return Object.freeze({
    storage: 'current-page-memory-only',
    upload: false,
    remoteLookup: false,
    automaticRightsVerification: false,
    fairUseClaim: false,
    publicationApproval: false,
    explicitExportOnly: true
  });
}
