export const DEFAULT_AI_PROVIDER_ID = 'guide';

export function isLocalAIProvider(provider = {}) {
  return LOCAL_PROVIDER_IDS.has(String(provider?.id || '').toLowerCase());
}

export function normalizeAIProviderId(providerId, fallback = DEFAULT_AI_PROVIDER_ID) {
  const id = String(providerId || '').trim();
  const candidate = PROVIDERS[id];
  return candidate && candidate.enabled !== false ? id : fallback;
}
