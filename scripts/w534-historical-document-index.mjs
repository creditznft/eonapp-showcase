#!/usr/bin/env node
/** Generates a deterministic index of preserved historical documentation without deleting provenance. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  W534_CURRENT_ENTRYPOINTS,
  W534_HISTORICAL_COLLECTIONS,
  W534_HISTORICAL_DOCUMENTATION_CONTRACT
} from '../config/w534-historical-documentation-contract.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = path.join(ROOT, W534_HISTORICAL_DOCUMENTATION_CONTRACT.generatedIndex);
const toPosix = (value) => String(value).replaceAll('\\', '/');
const exists = (target) => fs.existsSync(target);

function walkMarkdown(root, directory, output = []) {
  if (!exists(directory)) return output;
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) walkMarkdown(root, full, output);
    else if (entry.isFile() && /\.md$/i.test(entry.name)) output.push(toPosix(path.relative(root, full)));
  }
  return output;
}

function countMarkdown(root, relative) {
  return walkMarkdown(root, path.join(root, relative)).length;
}

export function buildW534HistoricalDocumentIndex({ root = ROOT } = {}) {
  const rootMarkdown = fs.readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /\.md$/i.test(entry.name))
    .map((entry) => entry.name)
    .filter((name) => !W534_CURRENT_ENTRYPOINTS.includes(name))
    .sort((a, b) => a.localeCompare(b));
  const collectionRows = W534_HISTORICAL_COLLECTIONS.map((relative) => ({ relative, markdownFiles: countMarkdown(root, relative) }));
  const rootLines = rootMarkdown.length
    ? rootMarkdown.map((relative) => `- \`${relative}\` — historical unless the current entrypoints explicitly link it.`)
    : ['- None.'];
  const lines = [
    '# W534 Historical Documentation Index',
    '',
    '> Generated by `node scripts/w534-historical-document-index.mjs --write`. Historical evidence is preserved for provenance, but it is not a current product, deployment, or release instruction.',
    '',
    '## Use these current entrypoints',
    '',
    ...W534_CURRENT_ENTRYPOINTS.map((relative) => `- \`${relative}\``),
    '',
    '## Preserved historical collections',
    '',
    '| Collection | Markdown files | How to use it |',
    '| --- | ---: | --- |',
    ...collectionRows.map(({ relative, markdownFiles }) => `| \`${relative}/\` | ${markdownFiles} | Archaeology/evidence only; do not treat as the current release plan. |`),
    '',
    '## Historical root-level Markdown files',
    '',
    ...rootLines,
    '',
    '## Retired runnable diagnostic',
    '',
    `- \`${W534_HISTORICAL_DOCUMENTATION_CONTRACT.retiredRunnableDiagnostic}\` is physically preserved under \`${W534_HISTORICAL_DOCUMENTATION_CONTRACT.quarantineRoot}/\` because it attempted to load retired P2P code. It is not part of the runnable E2E or current unit suite.`,
    '',
    '## Boundary',
    '',
    '- This index does not delete audit history or claim that historical plans were executed. It gives maintainers one current starting point and makes old instructions visibly secondary.'
  ];
  return `${lines.join('\n')}\n`;
}

function main() {
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  const expected = buildW534HistoricalDocumentIndex();
  const current = exists(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (mode === 'write') {
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, expected);
    console.log(JSON.stringify({ ok: true, mode, output: toPosix(path.relative(ROOT, OUTPUT)), bytes: Buffer.byteLength(expected) }, null, 2));
    return;
  }
  const ok = current === expected;
  console.log(JSON.stringify({ ok, mode, output: toPosix(path.relative(ROOT, OUTPUT)), reason: ok ? 'current' : 'index-stale-run-with-write' }, null, 2));
  if (!ok) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
